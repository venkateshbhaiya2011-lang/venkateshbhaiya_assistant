/**
 * Returns a deterministic quote for any given date based on calendar day.
 * Everyone visiting on that day sees the identical Daily Motivation quote!
 */
export function getDailyQuote(date: Date = new Date()): DailyMotivationQuote {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  const dateKey = `${year}-${month}-${day}`;

  // Simple string hash for consistent index across days
  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash << 5) - hash + dateKey.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % DAILY_MOTIVATION_QUOTES.length;
  return {
    ...DAILY_MOTIVATION_QUOTES[index],
    dateKey,
  };
}

/**
 * Returns a random quote excluding the given ID, useful for shuffle/refresh.
 */
export function getRandomQuote(excludeId?: string): DailyMotivationQuote {
  const pool = excludeId
    ? DAILY_MOTIVATION_QUOTES.filter((q) => q.id !== excludeId)
    : DAILY_MOTIVATION_QUOTES;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

export function formatQuoteDate(date: Date = new Date()): string {
  return date.toLocaleDateString("en-US", {
    weekday: "long",
    month: "short",
    day: "numeric",
  });
}

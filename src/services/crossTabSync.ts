import { UserAccount } from "../types";

export type AuthSyncMessageType =
  | "AUTH_LOGIN"
  | "AUTH_LOGOUT"
  | "AUTH_UPDATE"
  | "REQUEST_CURRENT_AUTH"
  | "AUTH_STATE_RESPONSE";

export interface AuthSyncPayload {
  type: AuthSyncMessageType;
  user?: UserAccount | null;
  senderTabId: string;
  timestamp: number;
}

type AuthCallback = (user: UserAccount | null, eventType: AuthSyncMessageType) => void;

// Unique identifier for this specific browser tab/window session
const TAB_ID: string =
  typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
    ? crypto.randomUUID()
    : "tab_" + Math.random().toString(36).slice(2, 9) + "_" + Date.now().toString(36);

const CHANNEL_NAME = "vb_cross_tab_auth_channel";
const STORAGE_SYNC_KEY = "vb_cross_tab_sync_event";

class CrossTabSyncManager {
  private channel: BroadcastChannel | null = null;
  private subscribers = new Set<AuthCallback>();
  private isInitialized = false;
  private lastProcessedTimestamp = 0;

  constructor() {
    this.init();
  }

  /**
   * Initializes the BroadcastChannel and multi-tiered cross-tab listeners
   */
  private init() {
    if (typeof window === "undefined" || this.isInitialized) return;
    this.isInitialized = true;

    // 1. Initialize BroadcastChannel API if supported
    if ("BroadcastChannel" in window) {
      try {
        this.channel = new BroadcastChannel(CHANNEL_NAME);
        this.channel.onmessage = (event: MessageEvent<AuthSyncPayload>) => {
          this.handleIncomingPayload(event.data);
        };
      } catch (err) {
        console.warn("[CrossTabSync] BroadcastChannel init warning, using storage fallback:", err);
        this.channel = null;
      }
    }

    // 2. Storage event fallback for cross-tab sync in sandboxed / legacy contexts
    window.addEventListener("storage", (event: StorageEvent) => {
      // Primary custom broadcast key
      if (event.key === STORAGE_SYNC_KEY && event.newValue) {
        try {
          const payload: AuthSyncPayload = JSON.parse(event.newValue);
          this.handleIncomingPayload(payload);
        } catch {}
      }

      // Direct vb_current_user fallback
      if (event.key === "vb_current_user") {
        try {
          const user: UserAccount | null = event.newValue ? JSON.parse(event.newValue) : null;
          this.notifySubscribers(user, user ? "AUTH_UPDATE" : "AUTH_LOGOUT");
        } catch {}
      }
    });

    // 3. Tab visibility / focus sync: When user switches back to this tab, verify sync
    document.addEventListener("visibilitychange", () => {
      if (document.visibilityState === "visible") {
        this.verifyAndRefreshState();
      }
    });

    window.addEventListener("focus", () => {
      this.verifyAndRefreshState();
    });

    // 4. Request latest active auth state from any existing tabs
    setTimeout(() => {
      this.requestCurrentAuthFromOtherTabs();
    }, 100);
  }

  /**
   * Routes and processes an incoming payload from another tab
   */
  private handleIncomingPayload(payload: AuthSyncPayload) {
    if (!payload || !payload.type) return;

    // Ignore messages generated by this exact tab
    if (payload.senderTabId === TAB_ID) return;

    // Reject older out-of-order messages
    if (payload.timestamp && payload.timestamp < this.lastProcessedTimestamp) {
      return;
    }
    if (payload.timestamp) {
      this.lastProcessedTimestamp = payload.timestamp;
    }

    switch (payload.type) {
      case "AUTH_LOGIN":
      case "AUTH_UPDATE": {
        const user = payload.user || null;
        this.syncLocalStorageUser(user);
        this.notifySubscribers(user, payload.type);
        break;
      }

      case "AUTH_LOGOUT": {
        this.syncLocalStorageUser(null);
        this.notifySubscribers(null, "AUTH_LOGOUT");
        break;
      }

      case "REQUEST_CURRENT_AUTH": {
        // Another tab just opened and requested the active auth state.
        // If this tab has an authenticated currentUser, respond immediately!
        try {
          const stored = localStorage.getItem("vb_current_user");
          if (stored) {
            const currentUser: UserAccount = JSON.parse(stored);
            if (currentUser && currentUser.id) {
              this.postPayload({
                type: "AUTH_STATE_RESPONSE",
                user: currentUser,
                senderTabId: TAB_ID,
                timestamp: Date.now(),
              });
            }
          }
        } catch {}
        break;
      }

      case "AUTH_STATE_RESPONSE": {
        const user = payload.user || null;
        if (user) {
          this.syncLocalStorageUser(user);
          this.notifySubscribers(user, "AUTH_STATE_RESPONSE");
        }
        break;
      }
    }
  }

  /**
   * Helper to write directly to localStorage without re-triggering storage event in this tab
   */
  private syncLocalStorageUser(user: UserAccount | null) {
    try {
      if (user) {
        localStorage.setItem("vb_current_user", JSON.stringify(user));
      } else {
        localStorage.removeItem("vb_current_user");
      }
    } catch {}
  }

  /**
   * Dispatches payload to BroadcastChannel and localStorage fallback
   */
  private postPayload(payload: AuthSyncPayload) {
    // 1. BroadcastChannel API
    if (this.channel) {
      try {
        this.channel.postMessage(payload);
      } catch (err) {
        console.warn("[CrossTabSync] channel.postMessage failed:", err);
      }
    }

    // 2. Storage event fallback (changes localStorage value to trigger 'storage' event across tabs)
    try {
      localStorage.setItem(STORAGE_SYNC_KEY, JSON.stringify(payload));
    } catch {}

    // 3. Intra-tab custom event
    if (typeof window !== "undefined") {
      window.dispatchEvent(
        new CustomEvent("vb_cross_tab_event", {
          detail: payload,
        })
      );
    }
  }

  /**
   * Broadcasts that a user has logged in
   */
  public broadcastLogin(user: UserAccount) {
    const payload: AuthSyncPayload = {
      type: "AUTH_LOGIN",
      user,
      senderTabId: TAB_ID,
      timestamp: Date.now(),
    };
    this.lastProcessedTimestamp = payload.timestamp;
    this.postPayload(payload);
  }

  /**
   * Broadcasts that the user has logged out
   */
  public broadcastLogout() {
    const payload: AuthSyncPayload = {
      type: "AUTH_LOGOUT",
      user: null,
      senderTabId: TAB_ID,
      timestamp: Date.now(),
    };
    this.lastProcessedTimestamp = payload.timestamp;
    this.postPayload(payload);
  }

  /**
   * Broadcasts user profile or preference updates
   */
  public broadcastUpdate(user: UserAccount) {
    const payload: AuthSyncPayload = {
      type: "AUTH_UPDATE",
      user,
      senderTabId: TAB_ID,
      timestamp: Date.now(),
    };
    this.lastProcessedTimestamp = payload.timestamp;
    this.postPayload(payload);
  }

  /**
   * Sends a request to all other open tabs to respond with their authenticated user state
   */
  public requestCurrentAuthFromOtherTabs() {
    const payload: AuthSyncPayload = {
      type: "REQUEST_CURRENT_AUTH",
      senderTabId: TAB_ID,
      timestamp: Date.now(),
    };
    this.postPayload(payload);
  }

  /**
   * Subscribes a listener to cross-tab auth state changes.
   * Returns an unsubscribe function.
   */
  public subscribe(callback: AuthCallback): () => void {
    this.subscribers.add(callback);
    return () => {
      this.subscribers.delete(callback);
    };
  }

  /**
   * Notifies all registered subscribers of an auth state change
   */
  private notifySubscribers(user: UserAccount | null, eventType: AuthSyncMessageType) {
    this.subscribers.forEach((cb) => {
      try {
        cb(user, eventType);
      } catch (err) {
        console.error("[CrossTabSync] subscriber notification error:", err);
      }
    });

    if (typeof window !== "undefined") {
      window.dispatchEvent(
        new CustomEvent("vb_account_synced", {
          detail: user,
        })
      );
    }
  }

  /**
   * Checks current localStorage state when tab regains focus or visibility
   */
  public verifyAndRefreshState(): UserAccount | null {
    try {
      const stored = localStorage.getItem("vb_current_user");
      const user: UserAccount | null = stored ? JSON.parse(stored) : null;
      return user;
    } catch {
      return null;
    }
  }

  /**
   * Returns the unique tab session ID
   */
  public getTabId(): string {
    return TAB_ID;
  }

  /**
   * Checks if native BroadcastChannel is active
   */
  public isChannelSupported(): boolean {
    return typeof window !== "undefined" && "BroadcastChannel" in window;
  }
}

export const CrossTabSync = new CrossTabSyncManager();
